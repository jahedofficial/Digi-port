import { ITelegramFormatter, ReportDocument } from './types';

/**
 * Production-Grade Telegram Alert & Report Formatter
 * Formats alerts and executive briefs into Telegram-compatible HTML.
 */
export class TelegramFormatter implements ITelegramFormatter {
  /**
   * Escape HTML special characters for Telegram HTML mode
   */
  private escapeHtml(text: string): string {
    return text
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;');
  }

  /**
   * Format a high-priority operational metric alert for Telegram
   */
  public formatAlert(title: string, metrics: Record<string, string | number>): string {
    const lines: string[] = [];
    lines.push(`🚨 <b>[DIGIPORT ALERT] ${this.escapeHtml(title)}</b>`);
    lines.push('');

    for (const [key, val] of Object.entries(metrics)) {
      const formattedKey = key
        .replace(/([A-Z])/g, ' $1')
        .replace(/^./, (str) => str.toUpperCase());

      let icon = '📊';
      const lower = key.toLowerCase();
      if (lower.includes('spend') || lower.includes('cost') || lower.includes('budget')) icon = '💵';
      else if (lower.includes('roas') || lower.includes('revenue')) icon = '📈';
      else if (lower.includes('cpa') || lower.includes('cpc')) icon = '🎯';
      else if (lower.includes('conversion')) icon = '⚡';
      else if (lower.includes('error') || lower.includes('issue') || lower.includes('fail')) icon = '⚠️';

      lines.push(`${icon} <b>${this.escapeHtml(formattedKey)}:</b> <code>${this.escapeHtml(String(val))}</code>`);
    }

    lines.push('');
    lines.push(`<i>Generated at: ${new Date().toISOString().replace('T', ' ').substring(0, 19)} UTC</i>`);

    return lines.join('\n');
  }

  /**
   * Format a concise executive report summary for Telegram dispatch
   */
  public formatReportSummary(report: ReportDocument): string {
    const lines: string[] = [];

    const gradeIcon =
      report.scorecard.grade === 'EXCELLENT'
        ? '🟢'
        : report.scorecard.grade === 'GOOD'
          ? '🔵'
          : report.scorecard.grade === 'ATTENTION_NEEDED'
            ? '🟡'
            : '🔴';

    lines.push(`📊 <b>${this.escapeHtml(report.title)}</b>`);
    lines.push(`Client: <code>${this.escapeHtml(report.clientId)}</code>`);
    lines.push(`Score: <b>${report.scorecard.overallScore}/100</b> ${gradeIcon} (<b>${report.scorecard.grade}</b>)`);
    lines.push(`Date Range: <code>${report.dateRange.startDate} → ${report.dateRange.endDate}</code>`);
    lines.push(`Channels: <code>${report.platforms.join(', ')}</code>`);
    lines.push('');

    // Brief executive highlight
    lines.push('<b>Executive Summary:</b>');
    lines.push(this.escapeHtml(report.executiveSummaryEnglish.substring(0, 300)) + (report.executiveSummaryEnglish.length > 300 ? '...' : ''));
    lines.push('');

    // Top Action Items
    if (report.actionPlan.length > 0) {
      lines.push('<b>Top Action Items:</b>');
      for (const item of report.actionPlan.slice(0, 3)) {
        lines.push(`• <b>[${item.priority}]</b> ${this.escapeHtml(item.title)}: <i>${this.escapeHtml(item.action)}</i>`);
      }
      lines.push('');
    }

    lines.push(`<i>Generated by DigiPort Universal AI OS</i>`);

    return lines.join('\n');
  }
}
